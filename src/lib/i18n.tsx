const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    if (typeof window !== "undefined") {
      const saved = localStorage.getItem("landvision_lang");
      if (saved && (saved in TRANSLATIONS)) return saved as LanguageCode;
    }
    return "en";
  });

  const setLanguage = (lang: LanguageCode) => {
    setLanguageState(lang);
    if (typeof window !== "undefined") {
      localStorage.setItem("landvision_lang", lang);
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === "ur" ? "rtl" : "ltr";
    }
  };

  useEffect(() => {
    if (typeof window !== "undefined") {
      document.documentElement.lang = language;
      document.documentElement.dir = language === "ur" ? "rtl" : "ltr";
    }
  }, [language]);

  const t = TRANSLATIONS[language] || TRANSLATIONS.en;
  const dir = language === "ur" ? "rtl" : "ltr";

  const tStr = (englishText: string): string => {
    if (language === "en") return englishText;
    const dict = PHRASE_DICTIONARY[language];
    if (dict && dict[englishText]) {
      return dict[englishText];
    }
    return englishText;
  };

  const formatNumberIndian = (num: number): string => {
    return new Intl.NumberFormat(language === "en" ? "en-IN" : `${language}-IN`, {
      maximumFractionDigits: 2,
    }).format(num);
  };

  const formatCurrencyCr = (amountCr: number): string => {
    const formatted = formatNumberIndian(amountCr);
    return `₹${formatted} ${t.dashboard.crore}`;
  };

  return (
    <I18nContext.Provider
      value={{
        language,
        setLanguage,
        t,
        tStr,
        dir,
        formatCurrencyCr,
        formatNumberIndian,
      }}
    >
      {children}
    </I18nContext.Provider>
  );
}

export function useTranslation() {
  const context = useContext(I18nContext);
  if (!context) {
    // Fallback if rendered outside provider
    return {
      language: "en" as LanguageCode,
      setLanguage: () => {},
      t: TRANSLATIONS.en,
      tStr: (s: string) => s,
      dir: "ltr" as const,
      formatCurrencyCr: (cr: number) => `₹${cr.toFixed(1)} Cr`,
      formatNumberIndian: (n: number) => n.toLocaleString("en-IN"),
    };
  }
  return context;
}

export function LanguageSelector({ className }: { className?: string }) {
  const { language, setLanguage } = useTranslation();

  return (
    <div className={`relative inline-flex items-center gap-1.5 shrink-0 ${className || ""}`}>
      <Globe className="size-3.5 text-muted-foreground shrink-0" aria-hidden="true" />
      <select
        value={language}
        onChange={(e) => setLanguage(e.target.value as LanguageCode)}
        className="h-8 rounded-lg border border-border bg-card px-2.5 text-xs font-semibold text-foreground focus:outline-none focus:ring-1 focus:ring-primary shadow-xs cursor-pointer max-w-[150px] sm:max-w-none"
        aria-label="Select Interface Language"
      >
        {SUPPORTED_LANGUAGES.map((lang) => (
          <option key={lang.code} value={lang.code}>
            {lang.nativeLabel} ({lang.label})
          </option>
        ))}
      </select>
    </div>
  );
}

